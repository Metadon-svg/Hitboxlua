local function vm_fail()
  error("VM fault")
end

local function vm_env_ok()
  if type(string) ~= "string" then return false end
  if type(string.byte) ~= "function" then return false end
  if type(string.char) ~= "function" then return false end
  if type(table) ~= "table" then return false end
  if type(table.concat) ~= "function" then return false end
  if type(pcall) ~= "function" then return false end

  -- Очень простая проверка на отладчик/хук.
  -- Если защищённый скрипт не запускается из-за этого блока,
  -- удали блок с debug и оставь только базовые проверки.
  if debug and debug.gethook then
    local ok, hook = pcall(debug.gethook)
    if ok and hook ~= nil then
      return false
    end
  end

  return true
end

local function vm_compile(src)
  -- Сначала пробуем loadstring, потому что во многих версиях
  -- это классический способ выполнить строку кода.
  local name_loadstring = string.char(108, 111, 97, 100, 115, 116, 114, 105, 110, 103) -- loadstring
  local f = rawget(_G, name_loadstring)

  if type(f) == "function" then
    return f(src, string.char(61, 86, 77)) -- "=VM"
  end

  -- Если loadstring нет, пробуем load.
  local name_load = string.char(108, 111, 97, 100) -- load
  f = rawget(_G, name_load)

  if type(f) == "function" then
    local done = false
    return f(function()
      if done then return nil end
      done = true
      return src
    end, string.char(61, 86, 77)) -- "=VM"
  end

  vm_fail()
end

local VM_STATE = {code = nil}
local VM_PROG = {OP.VERIFY, OP.INIT, OP.DECODE, OP.EXEC, OP.EXIT}
local pc = 1

while pc <= #VM_PROG do
  local ins = VM_PROG[pc]

  if ins == OP.VERIFY then
    if not vm_env_ok() then
      vm_fail()
    end
    pc = pc + 1

  elseif ins == OP.INIT then
    VM_STATE = {code = nil}
    pc = pc + 1

  elseif ins == OP.DECODE then
    local parts = {}
    local n = 0
    local klen = #VM_K
    local sbase = VM_S % 256

    for i = 1, #VM_P do
      local k = VM_K[((i - 1) % klen) + 1]
      local salt = (sbase + (((i - 1) % 256) * 31)) % 256
      local b = (VM_P[i] - k - salt) % 256

      n = n + 1
      parts[n] = string.char(b)
    end

    VM_STATE.code = table.concat(parts)

    -- По возможности затираем сырые данные.
    VM_P = nil
    VM_K = nil
    pc = pc + 1

  elseif ins == OP.EXEC then
    local src = VM_STATE.code
    VM_STATE.code = nil

    if type(src) ~= "string" then
      vm_fail()
    end

    local chunk, err = vm_compile(src)

    -- Сносим исходник до запуска.
    src = nil

    if type(chunk) ~= "function" then
      vm_fail()
    end

    if setfenv and getfenv then
      pcall(setfenv, chunk, getfenv(1))
    end

    chunk()
    pc = pc + 1

  elseif ins == OP.EXIT then
    break

